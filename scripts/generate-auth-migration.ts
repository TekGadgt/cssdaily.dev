/**
 * Generates the D1 migration for Better Auth's tables from the SAME options
 * the Worker runs (src/lib/auth-options.ts), against an empty in-memory
 * SQLite database — no CLI version drift, no live database.
 *
 *   npx tsx scripts/generate-auth-migration.ts > migrations/0003_auth.sql
 *
 * Review the output by hand: additions only.
 */
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../src/lib/auth-options';

const options = {
  ...authOptions({
    baseURL: 'https://cssdaily.dev',
    secret: 'schema-generation-only-not-a-real-secret-000000',
    githubClientId: 'unused',
    githubClientSecret: 'unused',
  }),
  database: new DatabaseSync(':memory:'),
};

const { compileMigrations, unsafeChanges, schemaProblems } = await getMigrations(options as never, { throwOnUnsafe: false });
if (unsafeChanges.length || schemaProblems.length) {
  console.error('Refusing to generate:', [...unsafeChanges, ...schemaProblems].join('\n'));
  process.exit(1);
}
const sql = await compileMigrations();
const version = JSON.parse(readFileSync('node_modules/better-auth/package.json', 'utf8')).version;
process.stdout.write(`-- Better Auth ${version} schema,
-- generated by scripts/generate-auth-migration.ts from src/lib/auth-options.ts.
${sql.trim()}

-- Deletion tombstones: Better Auth's random internal user id only (not
-- personal data). After any restore from backup, every id listed here is
-- deleted again so a restore can't resurrect a deleted account.
CREATE TABLE account_deletions (
  user_id    TEXT    PRIMARY KEY,
  deleted_at INTEGER NOT NULL
);
`);
